using System.Reflection;

namespace PureQL.CSharp.Model.Serialization.Generator;

/// <summary>
/// Emits the readers and writers of every model type as the partial class
/// <c>ModelSerializers</c>, one file per model namespace, with the
/// <c>Signatures</c> the unions dispatch on, the encoded property <c>Names</c> and the
/// registration of every converter.
/// </summary>
internal sealed class Emitter(ModelCatalog catalog, string modelVersion)
{
    /// <summary>The unions read by hand, by which properties are present.</summary>
    private static readonly string[] HandReadUnions =
    [
        nameof(PureQLQuery),
        nameof(Query),
        nameof(From),
        nameof(Join),
        nameof(PaginationSkip),
        nameof(PaginationTake),
    ];

    /// <summary>The unions written by hand: a number or a parameter.</summary>
    private static readonly string[] HandWrittenUnions =
    [
        nameof(PaginationSkip),
        nameof(PaginationTake),
    ];

    /// <summary>Names that C# reads as a keyword where a local is declared or used.</summary>
    private static readonly string[] Keywords =
    [
        "else",
        "from",
        "group",
        "if",
        "in",
        "join",
        "on",
        "operator",
        "select",
        "where",
    ];

    private readonly ModelCatalog _catalog = catalog;

    private readonly string _modelVersion = modelVersion;

    private readonly Dictionary<string, RecordModel> _records = catalog.Records.ToDictionary(
        r => r.Type.Name,
        StringComparer.Ordinal
    );

    public static string Local(string json)
    {
        return Keywords.Contains(json) ? "@" + json : json;
    }

    public SortedDictionary<string, string> Emit()
    {
        SortedDictionary<string, string> files = [with(StringComparer.Ordinal)];
        foreach (
            IGrouping<string, Type> group in _catalog
                .Records.Select(r => r.Type)
                .Concat(_catalog.Unions.Select(u => u.Type))
                .GroupBy(Namespace)
                .OrderBy(g => g.Key, StringComparer.Ordinal)
        )
        {
            files[$"ModelSerializers.{group.Key}.g.cs"] = Serializers(group.Key);
        }

        files["ModelSerializers.Registrations.g.cs"] = Registrations();
        files["Signatures.g.cs"] = Signatures();
        files["Names.g.cs"] = Names();
        return files;
    }

    private static string Namespace(Type type)
    {
        string name = type.Namespace!;
        return name == typeof(PureQLQuery).Namespace ? "Queries" : name[(name.LastIndexOf('.') + 1)..];
    }

    private CodeWriter Header(params string[] usings)
    {
        CodeWriter code = new CodeWriter();
        code.Line("// <auto-generated>");
        code.Line("// Generated by PureQL.CSharp.Model.Serialization.Generator from");
        code.Line($"// PureQL.CSharp.Model {_modelVersion}. Do not edit: change the generator");
        code.Line("// and run it again.");
        code.Line("// </auto-generated>");
        code.Line("#nullable enable");
        code.Line();
        foreach (string name in usings)
        {
            code.Line($"using {name};");
        }

        if (usings.Length > 0)
        {
            code.Line();
        }

        code.Line("namespace PureQL.CSharp.Model.Serialization;");
        code.Line();
        return code;
    }

    private string[] ModelUsings()
    {
        return
        [
            "System.Text.Json",
            .. _catalog
                .Records.Select(r => r.Type.Namespace!)
                .Concat(_catalog.Unions.Select(u => u.Type.Namespace!))
                .Where(n => n != typeof(PureQLQuery).Namespace)
                .Distinct()
                .Order(StringComparer.Ordinal),
            "PureQL.CSharp.Model.Serialization.Literals",
        ];
    }

    private string Serializers(string ns)
    {
        CodeWriter code = Header(ModelUsings());
        code.Open("internal static partial class ModelSerializers");
        bool first = true;
        foreach (RecordModel record in _catalog.Records.Where(r => Namespace(r.Type) == ns))
        {
            Separate(code, ref first);
            Shape(code, record);
            code.Line();
            RecordReader(code, record);
            code.Line();
            RecordWriter(code, record);
        }

        foreach (UnionModel union in _catalog.Unions.Where(u => Namespace(u.Type) == ns))
        {
            if (!HandReadUnions.Contains(union.Type.Name))
            {
                Separate(code, ref first);
                UnionReader(code, union);
            }

            if (!HandWrittenUnions.Contains(union.Type.Name))
            {
                Separate(code, ref first);
                UnionWriter(code, union);
            }
        }

        code.Close();
        return code.ToString();
    }

    private static void Separate(CodeWriter code, ref bool first)
    {
        if (!first)
        {
            code.Line();
        }

        first = false;
    }

    private static void Shape(CodeWriter code, RecordModel record)
    {
        string name = record.Type.Name;
        ulong required = 0;
        for (int i = 0; i < record.Properties.Count; i++)
        {
            required |= record.Properties[i].IsRequired ? 1UL << i : 0;
        }

        string properties = $"[{string.Join(", ", record.Properties.Select(p => $"\"{p.Json}\""))}]";
        code.Call(
            $"private static readonly RecordShape {name}Shape = new RecordShape",
            [
                $"nameof({name})",
                $"Kinds.{record.Kind}",
                record.DeclaredType is null ? "TypeIds.None" : $"TypeIds.{record.DeclaredType}",
                properties == "[]" ? "[]" : properties,
                $"0b{Convert.ToString((long)required, 2)}",
            ],
            ";"
        );
    }

    private static void RecordReader(CodeWriter code, RecordModel record)
    {
        string name = record.Type.Name;
        Signature(code, $"internal static {name} Read{name}", "ref Utf8JsonReader reader", "ReadContext context");
        code.Line("{");
        code.Indent();
        code.Line($"ObjectScope scope = context.Begin(ref reader, {name}Shape);");
        foreach (PropertyModel property in record.Properties)
        {
            string? declaration = Declaration(property);
            if (declaration is not null)
            {
                code.Line(declaration);
            }
        }

        if (record.Properties.Count == 0)
        {
            code.Open("while (context.Next(ref reader, ref scope, out _))");
            code.Close();
        }
        else
        {
            code.Open("while (context.Next(ref reader, ref scope, out int property))");
            code.Open("switch (property)");
            for (int i = 0; i < record.Properties.Count; i++)
            {
                code.Line($"case {i}:");
                code.Indent();
                ReadStatement(code, record.Properties[i]);
                code.Line("break;");
                code.Outdent();
            }

            code.Close();
            code.Close();
        }

        code.Line();
        code.Line("context.End(ref scope);");
        if (record.NullableCause is not null)
        {
            code.Wrap("if (!(", record.NullableCause, "))");
            code.Line("{");
            code.Indent();
            code.Line($"throw context.NotNullable({name}Shape);");
            code.Outdent();
            code.Line("}");
            code.Line();
        }

        Dictionary<string, PropertyModel> byJson = record.Properties.ToDictionary(
            p => p.Json,
            StringComparer.Ordinal
        );
        code.Call(
            $"return new {name}",
            [.. record.Arguments.Select(a => Argument(byJson[a]))],
            ";"
        );
        code.Outdent();
        code.Line("}");
    }

    private static void Signature(CodeWriter code, string head, params string[] parameters)
    {
        code.Call(head, parameters, "");
    }

    private static string? Declaration(PropertyModel property)
    {
        string local = Local(property.Json);
        string type = TypeName(property.Type);
        return property.Kind switch
        {
            ValueKind.Union => $"{type} {local} = default;",
            ValueKind.OptionalUnion or ValueKind.Record => $"{type}? {local} = null;",
            ValueKind.Many or ValueKind.OptionalMany or ValueKind.LiteralList => $"{type}[]? {local} = null;",
            ValueKind.Strings or ValueKind.OptionalStrings => $"string[]? {local} = null;",
            ValueKind.String or ValueKind.OptionalString => $"string? {local} = null;",
            ValueKind.Over => $"AggregateOver {local} = AggregateOver.Group;",
            ValueKind.Direction => $"SortDirection {local} = SortDirection.Asc;",
            ValueKind.JoinKind => $"JoinKind {local} = default;",
            ValueKind.Literal when property.Type == typeof(string) => $"string? {local} = null;",
            ValueKind.Literal => $"{type} {local} = default;",
            ValueKind.NullLiteral => null,
            _ => throw new InvalidOperationException($"{property.Kind} has no local."),
        };
    }

    private static void ReadStatement(CodeWriter code, PropertyModel property)
    {
        string local = Local(property.Json);
        string type = property.Type.Name;
        if (property.Kind == ValueKind.NullLiteral)
        {
            code.Line("context.Null(ref reader);");
            return;
        }

        string value = property.Kind switch
        {
            ValueKind.Union or ValueKind.OptionalUnion or ValueKind.Record => $"Read{type}(ref reader, context)",
            ValueKind.Many or ValueKind.OptionalMany => $"context.Many(ref reader, {property.MinItems}, Read{type})",
            ValueKind.Strings or ValueKind.OptionalStrings => "context.Strings(ref reader)",
            ValueKind.String or ValueKind.OptionalString => "context.String(ref reader)",
            ValueKind.Over => "context.Over(ref reader)",
            ValueKind.Direction => "context.Direction(ref reader)",
            ValueKind.JoinKind => "context.Kind(ref reader)",
            ValueKind.Literal => $"LiteralValues.{property.Literal}.Read(ref reader, context)",
            ValueKind.LiteralList => $"context.Values(ref reader, LiteralValues.{property.Literal})",
            ValueKind.NullLiteral => throw new InvalidOperationException("A null has no value."),
            _ => throw new InvalidOperationException($"{property.Kind} cannot be read."),
        };
        code.Wrap($"{local} = ", value, ";");
    }

    private static string Argument(PropertyModel property)
    {
        string local = Local(property.Json);
        return property.Kind switch
        {
            ValueKind.Record or ValueKind.Many or ValueKind.Strings or ValueKind.String or ValueKind.LiteralList => local + "!",
            ValueKind.Literal when property.Type == typeof(string) => local + "!",
            ValueKind.Union or ValueKind.OptionalUnion or ValueKind.OptionalMany
            or ValueKind.OptionalStrings or ValueKind.OptionalString or ValueKind.Over
            or ValueKind.Direction or ValueKind.JoinKind or ValueKind.Literal
            or ValueKind.NullLiteral => local,
            _ => local,
        };
    }

    private static void RecordWriter(CodeWriter code, RecordModel record)
    {
        string name = record.Type.Name;
        Signature(code, $"internal static void Write{name}", "Utf8JsonWriter writer", $"{name} value");
        code.Line("{");
        code.Indent();
        code.Line("writer.WriteStartObject();");
        bool typeFirst = record.IsOperator || (record.Kind == "Literal");
        if (record.IsOperator)
        {
            code.Line($"Writes.Operator(writer, Kinds.{record.Kind});");
        }

        if (typeFirst && (record.DeclaredType is not null))
        {
            code.Line($"Writes.Type(writer, TypeIds.{record.DeclaredType});");
        }

        foreach (PropertyModel property in record.Properties)
        {
            WriteStatement(code, property);
        }

        if (!typeFirst && (record.DeclaredType is not null))
        {
            code.Line($"Writes.Type(writer, TypeIds.{record.DeclaredType});");
        }

        code.Line("writer.WriteEndObject();");
        code.Outdent();
        code.Line("}");
    }

    private static void WriteStatement(CodeWriter code, PropertyModel property)
    {
        string type = property.Type.Name;
        string value = $"value.{property.Name}";
        string name = $"Names.{property.Name}";
        switch (property.Kind)
        {
            case ValueKind.Union:
                code.Line($"writer.WritePropertyName({name});");
                code.Line($"Write{type}(writer, {value});");
                break;
            case ValueKind.OptionalUnion:
                code.Call("Writes.Optional", ["writer", name, value, $"Write{type}"], ";");
                break;
            case ValueKind.Record:
                code.Line($"writer.WritePropertyName({name});");
                code.Call($"Write{type}", ["writer", $"Writes.NotNull({value})"], ";");
                break;
            case ValueKind.Many:
                code.Call("Writes.Many", ["writer", name, value, $"Write{type}"], ";");
                break;
            case ValueKind.OptionalMany:
                code.Call("Writes.OptionalMany", ["writer", name, value, $"Write{type}"], ";");
                break;
            case ValueKind.Strings:
                code.Call("Writes.Strings", ["writer", name, value], ";");
                break;
            case ValueKind.OptionalStrings:
                code.Call("Writes.OptionalStrings", ["writer", name, value], ";");
                break;
            case ValueKind.String:
                code.Call("Writes.String", ["writer", name, value], ";");
                break;
            case ValueKind.OptionalString:
                code.Call("Writes.OptionalString", ["writer", name, value], ";");
                break;
            case ValueKind.Over:
                code.Line($"Writes.Over(writer, {value});");
                break;
            case ValueKind.Direction:
                code.Line($"Writes.Direction(writer, {value});");
                break;
            case ValueKind.JoinKind:
                code.Line($"Writes.Kind(writer, {value});");
                break;
            case ValueKind.Literal:
                code.Call("Writes.Value", ["writer", $"LiteralValues.{property.Literal}", value], ";");
                break;
            case ValueKind.LiteralList:
                code.Call("Writes.Values", ["writer", $"LiteralValues.{property.Literal}", value], ";");
                break;
            case ValueKind.NullLiteral:
                code.Line("Writes.Null(writer);");
                break;
            default:
                throw new InvalidOperationException($"{property.Kind} cannot be written.");
        }
    }

    private void UnionReader(CodeWriter code, UnionModel union)
    {
        string name = union.Type.Name;
        Dictionary<(string, string, string?), string> signatures = [];
        Signature(code, $"internal static {name} Read{name}", "ref Utf8JsonReader reader", "ReadContext context");
        code.Line("{");
        code.Indent();
        code.Wrap("int signature = ", $"context.Signature(ref reader, nameof({name}));", "");
        code.Line("return signature switch");
        code.Line("{");
        code.Indent();
        foreach (Type caseType in union.Cases)
        {
            RecordModel record = _records.TryGetValue(caseType.Name, out RecordModel? found)
                ? found
                : throw new InvalidOperationException($"{name} holds {caseType.Name}, which is not a record.");
            if ((record.Kind == "Unknown") || (record.DeclaredType is null))
            {
                throw new InvalidOperationException($"{name} holds {caseType.Name}, which has no signature.");
            }

            if (!signatures.TryAdd((record.Kind, record.DeclaredType, record.Family), caseType.Name))
            {
                throw new InvalidOperationException(
                    $"{name}: {caseType.Name} has the signature of {signatures[(record.Kind, record.DeclaredType, record.Family)]}."
                );
            }

            string arm = $"Signatures.{record.Signature} => ";
            string read = $"new {name}(Read{caseType.Name}(ref reader, context)),";
            if (((3 * 4) + arm.Length + read.Length) <= CodeWriter.MaxLineLength)
            {
                code.Line(arm + read);
            }
            else
            {
                code.Line($"{arm}new {name}(");
                code.Indent();
                code.Line($"Read{caseType.Name}(ref reader, context)");
                code.Outdent();
                code.Line("),");
            }
        }

        code.Line($"_ => throw context.NotAccepted(nameof({name}), signature),");
        code.Outdent();
        code.Line("};");
        code.Outdent();
        code.Line("}");
    }

    private static void UnionWriter(CodeWriter code, UnionModel union)
    {
        string name = union.Type.Name;
        Signature(code, $"internal static void Write{name}", "Utf8JsonWriter writer", $"{name} value");
        code.Line("{");
        code.Indent();
        code.Line("Writes.Record(writer, value.Value);");
        code.Outdent();
        code.Line("}");
    }

    private string Registrations()
    {
        CodeWriter code = Header(ModelUsings());
        code.Open("internal static partial class ModelSerializers");
        code.Line("/// <summary>Registers the converter of every model type.</summary>");
        code.Open("public static void Register(ModelRegistry registry)");
        foreach (RecordModel record in _catalog.Records)
        {
            string name = record.Type.Name;
            code.Call(
                $"registry.Record<{name}>",
                record.Nullable
                    ? [$"Read{name}", $"Write{name}", "nullable: true"]
                    : [$"Read{name}", $"Write{name}"],
                ";"
            );
        }

        foreach (UnionModel union in _catalog.Unions)
        {
            string name = union.Type.Name;
            code.Call($"registry.Union<{name}>", [$"Read{name}", $"Write{name}"], ";");
        }

        code.Close();
        code.Close();
        return code.ToString();
    }

    private string Signatures()
    {
        CodeWriter code = Header();
        code.Line("/// <summary>");
        code.Line("/// The signature of every case of a union: the kind of node, its declared type");
        code.Line("/// and, for a comparison, the family of its operand (see <see cref=\"Signature\"/>).");
        code.Line("/// </summary>");
        code.Open("internal static class Signatures");
        Dictionary<string, (string, string, string?)> constants = [with(StringComparer.Ordinal)];
        foreach (UnionModel union in _catalog.Unions.Where(u => !HandReadUnions.Contains(u.Type.Name)))
        {
            foreach (Type caseType in union.Cases)
            {
                RecordModel record = _records[caseType.Name];
                (string, string, string?) signature = (record.Kind, record.DeclaredType!, record.Family);
                if (constants.TryGetValue(record.Signature, out (string, string, string?) known))
                {
                    if (known != signature)
                    {
                        throw new InvalidOperationException($"{record.Signature} names two signatures.");
                    }

                    continue;
                }

                constants[record.Signature] = signature;
            }
        }

        if (constants.Values.Distinct().Count() != constants.Count)
        {
            throw new InvalidOperationException("Two signature constants are equal.");
        }

        bool first = true;
        foreach (KeyValuePair<string, (string Kind, string Type, string? Family)> constant in constants.OrderBy(c => c.Key, StringComparer.Ordinal))
        {
            Separate(code, ref first);
            string value = $"(Kinds.{constant.Value.Kind} << 16) | (TypeIds.{constant.Value.Type} << 8)";
            value += constant.Value.Family is null ? "" : $" | Families.{constant.Value.Family}";
            code.Wrap($"public const int {constant.Key} = ", value, ";");
        }

        code.Close();
        return code.ToString();
    }

    private string Names()
    {
        CodeWriter code = Header("System.Text.Json");
        code.Line("/// <summary>The JSON property names of the records, encoded once.</summary>");
        code.Open("internal static class Names");
        bool first = true;
        foreach (
            PropertyModel property in _catalog
                .Records.SelectMany(r => r.Properties)
                .Where(p => p.Kind is not (ValueKind.Literal or ValueKind.LiteralList or ValueKind.NullLiteral or ValueKind.Over or ValueKind.Direction or ValueKind.JoinKind))
                .DistinctBy(p => p.Name)
                .OrderBy(p => p.Name, StringComparer.Ordinal)
        )
        {
            Separate(code, ref first);
            code.Wrap(
                $"public static readonly JsonEncodedText {property.Name} = ",
                $"JsonEncodedText.Encode(\"{property.Json}\");",
                ""
            );
        }

        code.Close();
        return code.ToString();
    }

    private static string TypeName(Type type)
    {
        return type == typeof(long) ? "long"
            : type == typeof(decimal) ? "decimal"
            : type == typeof(bool) ? "bool"
            : type == typeof(string) ? "string"
            : type.Name;
    }

    /// <summary>The version of the model the code is generated from.</summary>
    public static string VersionOf(Assembly model)
    {
        string version =
            model.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion
            ?? model.GetName().Version!.ToString();
        int metadata = version.IndexOf('+', StringComparison.Ordinal);
        return metadata < 0 ? version : version[..metadata];
    }
}
